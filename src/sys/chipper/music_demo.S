.section .rodata,"a",@progbits

.global music_demo_ptrs
music_demo_ptrs:
    .short CHANNEL_0, CHANNEL_1, CHANNEL_2, CHANNEL_3

CHANNEL_0:
    DO 0
    PATTERN ENVIROS
    PATTERN PATTERN_00
    LOOP
    CHAN_STOP

CHANNEL_1:
    DO 0
    PATTERN ENVIROS
